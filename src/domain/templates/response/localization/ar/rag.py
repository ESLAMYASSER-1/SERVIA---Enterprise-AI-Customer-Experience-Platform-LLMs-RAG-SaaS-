def user_prompt(prompt: str, docs: list):
    userPrompt = []
    for i, doc in enumerate(docs, 1):
        userPrompt.append(
            "\n".join([
                f"[المستند {i}]",
                f"-> {doc.text}"
            ])
        )

    userPrompt.append(
        "\n".join(
            [
                "",
                "السؤال:",
                f"{prompt}"
            ]
        )
    )

    return "\n".join(userPrompt)
